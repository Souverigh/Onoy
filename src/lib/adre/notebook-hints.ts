/**
 * Клиенты магазина — подсказка к почерку: «Каныкей» в списке помогает не
 * прочитать «Каныкей эне». Имена не подставляются насильно: человека нет в
 * списке — пишется как в тетради (перенос и создаёт новых клиентов).
 */
export function notebookNamesPrompt(names: string[]): string {
  const list = [...new Set(names.map((n) => n.replace(/\s+/g, " ").trim()).filter(Boolean))].slice(0, 500);
  return `Клиенты, которые уже есть у магазина: ${list.join("; ")}. Если имя в тетради - это человек из этого списка (почерк похож), пиши имя точно как в списке. Если такого нет - пиши как в тетради, не подгоняй под список.`;
}
